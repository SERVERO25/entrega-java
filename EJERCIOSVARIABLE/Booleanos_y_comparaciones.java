package ejecicios;

public class Booleanos_y_comparaciones {

	public static void main(String[] args) {
		
		// ------------------Booleanos y comparaciones------------------
		// Basicamente es poner a prueba los conocimientos sobre los boleanos
		
		int a = 12 , b = 5 ;
		
		System.out.println("a>b = " + (a > b));
		System.out.println("a==b = " +(a == b));
		System.out.println("a%b==0 = "+ ((a % b) == 0));
		System.out.println("a>b && b>0 = " + (a > b && b > 0));

	}

}
